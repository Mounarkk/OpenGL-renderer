class Cube {
public:
  explicit Cube(const glm::vec3 position)
      : mPosition(position), mVAO(VertexArray()),
        mVBO(VertexBuffer(vertices, sizeof(vertices))){};
  virtual ~Cube() = default;
  virtual void draw(const Shader &shader, const Camera &camera) const = 0;

protected:
  const glm::vec3 mPosition;
  const VertexArray mVAO;
  const VertexBuffer mVBO;
};

class TexturedCube final : public Cube {
public:
  TexturedCube(const glm::vec3 &position, const std::string &texturePath);
  ~TexturedCube() override = default;
  void draw(const Shader &shader, const Camera &camera) const override;

private:
  Texture mTexture;
};

class ColoredCube final : public Cube {
public:
  ColoredCube(const glm::vec3 &position, glm::vec3 color);
  ~ColoredCube() override = default;
  void draw(const Shader &shader, const Camera &camera) const override;

private:
  glm::vec3 mColor;
};

