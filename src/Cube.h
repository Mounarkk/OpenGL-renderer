class Cube {
public:
  Cube(const glm::vec3 position) : mPosition(position), mVAO(VertexArray()){};
  virtual ~Cube() = default;
  virtual void draw(const Shader &shader, const Camera &camera) const = 0;

protected:
  const glm::vec3 mPosition;
  VertexArray mVAO;
};

class TexturedCube final : protected Cube {
public:
  TexturedCube(const glm::vec3 &position, const std::string &diffusePath,
               int diffuseFormat, const std::string &specularPath,
               int specularFormat, const std::string &emissionPath,
               int emissionFormat);
  ~TexturedCube() override = default;
  void draw(const Shader &shader, const Camera &camera) const override;

private:
  VertexBuffer mVBO;
  Texture mDiffuseTexture;
  Texture mSpecularTexture;
  Texture mEmissionTexture;
};

class ColoredCube final : protected Cube {
public:
  ColoredCube(const glm::vec3 &position, glm::vec3 color);
  ~ColoredCube() override = default;
  void draw(const Shader &shader, const Camera &camera) const override;

private:
  VertexBuffer mVBO;
  glm::vec3 mColor;
};
